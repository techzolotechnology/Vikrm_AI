def test_project_generator_normalization():
    print("\n► STEP 7 — VERIFYING PROJECT GENERATOR { files: [] } TRANSFORM...")

    raw_project_obj = {
        "files": [
            {"path": "src/App.tsx", "content": 'export function App() { return <h1>Netflix Clone</h1>; }'},
            {"path": "src/index.css", "content": "body { background: black; }"},
        ]
    }

    transformed = normalize_content_chunk(raw_project_obj)
    assert isinstance(transformed, str), "Transformed project generator output is not string"
    assert "### src/App.tsx" in transformed, "Missing Markdown header for App.tsx"
    assert "```tsx" in transformed, "Missing tsx code block for App.tsx"
    assert "### src/index.css" in transformed, "Missing Markdown header for index.css"
    assert "[object Object]" not in transformed, "Project generator output contains [object Object]"

    print("  ✓ Project Generator { files: [] } payload successfully transformed into Markdown code blocks")


