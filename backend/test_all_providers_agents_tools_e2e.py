def test_provider_chat_response_types():
    print("► STEP 4 — VERIFYING ALL LLM PROVIDERS RETURN STRING ChatResponse...")

    providers = [
        ("ollama", OllamaProvider()),
        ("openai", OpenAIProvider()),
        ("anthropic", AnthropicProvider()),
        ("gemini", GeminiProvider()),
        ("groq", GroqProvider()),
        ("deepseek", DeepSeekProvider()),
        ("qwen", QwenProvider()),
        ("mistral", MistralProvider()),
        ("openrouter", OpenRouterProvider()),
    ]

    for name, p in providers:
        # Test normalizer wrapper on dummy outputs
        out1 = normalize_content_chunk({"message": {"content": f"Hello from {name}"}})
        out2 = normalize_content_chunk({"files": [{"path": "App.tsx", "content": "export default App"}]})

        assert isinstance(out1, str), f"Provider {name} output 1 is not a string"
        assert isinstance(out2, str), f"Provider {name} output 2 is not a string"
        assert "[object Object]" not in out1, f"Provider {name} contains [object Object]"
        assert "[object Object]" not in out2, f"Provider {name} contains [object Object]"
        assert "### App.tsx" in out2, f"Provider {name} failed to format files block"
        print(f"  ✓ Provider [{name:<10}] ChatResponse contract verified")


